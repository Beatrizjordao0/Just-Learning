def é_hipotenusa(h):
    for c1 in range(1, h):
        for c2 in range(c1, h):
          if h**2 == (c1**2) + (c2**2):
            return True
    return False
#////////////////////////////////////////////////////////////////////////////////////////////////
def soma_hipotenusas(n):
    soma = 0  
    for numero in range(1, n + 1):     
        if é_hipotenusa(numero):
            soma += numero
    return soma
